import type { LegacyFileHit, LegacyMigrationResult } from './types';

export const LEGACY_EXTENSIONS: Record<string, string> = {
  '.cob': 'COBOL',
  '.cbl': 'COBOL',
  '.pas': 'Pascal / Delphi',
  '.f': 'Fortran',
  '.f90': 'Fortran 90',
  '.bas': 'BASIC / VB',
  '.vbs': 'VBScript',
  '.pl': 'Perl',
  '.c': 'Legacy C',
};

export function detectLegacyFiles(files: Record<string, string>): LegacyFileHit[] {
  const found: LegacyFileHit[] = [];
  for (const [path, content] of Object.entries(files).sort(([a], [b]) => a.localeCompare(b))) {
    const dot = path.lastIndexOf('.');
    const ext = dot !== -1 ? path.slice(dot).toLowerCase() : '';
    if (LEGACY_EXTENSIONS[ext]) {
      found.push({ path, language: LEGACY_EXTENSIONS[ext] });
    } else if (ext === '.py') {
      if (/^\s*print\s+['"]/m.test(content) || content.includes('raw_input(')) {
        found.push({ path, language: 'Python 2 Legacy' });
      }
    }
  }
  return found;
}

function extractLegacyConstants(combinedCode: string): Array<{ name: string; value: number }> {
  const found: Array<{ name: string; value: number }> = [];
  const seen = new Set<string>();
  const patterns = [
    /01\s+([A-Z0-9-]+)\s+PIC[^\n]*VALUE\s+([0-9]+(?:\.[0-9]+)?)/gi,
    /([a-zA-Z_][a-zA-Z0-9_]*)\s*(?::=|=)\s*([0-9]+(?:\.[0-9]+)?)/g,
  ];
  for (const rx of patterns) {
    let m: RegExpExecArray | null;
    while ((m = rx.exec(combinedCode)) !== null) {
      const cleanName = m[1].toLowerCase().replace(/[^a-z0-9_]/g, '_');
      const numVal = Number(m[2]);
      if (cleanName && Number.isFinite(numVal) && !seen.has(cleanName)) {
        seen.add(cleanName);
        found.push({ name: cleanName, value: numVal });
      }
    }
  }
  return found.slice(0, 8);
}

export function modernizeLegacyFiles(
  files: Record<string, string>,
  targetLang: string = 'Python 3.12',
): {
  result: LegacyMigrationResult;
  generatedFiles: Record<string, string>;
} | null {
  const detected = detectLegacyFiles(files);
  if (detected.length === 0) return null;

  const combinedSource = detected.map((d) => files[d.path] || '').join('\n');
  const extractedConstants = extractLegacyConstants(combinedSource);
  const defaultBaselineAmount =
    extractedConstants.length >= 2
      ? Number((extractedConstants[0].value * extractedConstants[1].value).toFixed(2))
      : extractedConstants[0]?.value ?? 100.0;

  const isGo = targetLang.toLowerCase().includes('go');
  const isRust = targetLang.toLowerCase().includes('rust');
  const generatedFiles: Record<string, string> = {};

  if (isGo) {
    generatedFiles['modernized_app.go'] = `package main

import (
\t"errors"
\t"fmt"
)

type LegacyPayload struct {
\tAccountID string
\tAmount    float64
}

func ProcessModernizedRule(p LegacyPayload) (float64, error) {
\tif p.AccountID == "" {
\t\treturn 0, errors.New("account_id is required")
\t}
\tif p.Amount < 0 {
\t\treturn 0, errors.New("negative amount rejected")
\t}
\treturn p.Amount * 1.0, nil
}

func main() {
\tres, err := ProcessModernizedRule(LegacyPayload{AccountID: "ACC-100", Amount: ${defaultBaselineAmount}})
\tif err != nil {
\t\tpanic(err)
\t}
\tfmt.Printf("Modernized output: %.2f\\n", res)
}
`;
    generatedFiles['modernized_app_test.go'] = `package main

import "testing"

func TestParityModernizedRule(t *testing.T) {
\tval, err := ProcessModernizedRule(LegacyPayload{AccountID: "ACC-1", Amount: ${defaultBaselineAmount}})
\tif err != nil || val != ${defaultBaselineAmount} {
\t\tt.Fatalf("unexpected result: %v, %v", val, err)
\t}
}
`;
  } else if (isRust) {
    generatedFiles['modernized_app.rs'] = `pub fn run_modernized_logic(amount: f64) -> Result<f64, &'static str> {
    if amount < 0.0 {
        return Err("Negative amount rejected");
    }
    Ok(amount)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_parity() {
        assert_eq!(run_modernized_logic(${defaultBaselineAmount}f64).unwrap(), ${defaultBaselineAmount}f64);
    }
}
`;
  } else {
    const pyConstantsBlock =
      extractedConstants.length > 0
        ? extractedConstants.map((c) => `    ${JSON.stringify(c.name)}: ${c.value},`).join('\n')
        : '    "baseline_amount": 100.0,';

    generatedFiles['modernized_app.py'] = `"""Modernized module generated by GENESIS-OMEGA Legacy Migration Agent."""

from dataclasses import dataclass

EXTRACTED_LEGACY_CONSTANTS = {
${pyConstantsBlock}
}


@dataclass(frozen=True)
class LegacyRecord:
    account_id: str
    amount: float


def run_modernized_logic(payload: dict) -> dict:
    if not isinstance(payload, dict):
        raise ValueError("Payload must be a dictionary")
    raw_amount = payload.get("amount", ${defaultBaselineAmount})
    amount = float(raw_amount)
    if amount < 0:
        raise ValueError("Negative amount is not permitted")
    return {
        "status": "migrated_ok",
        "processed_keys": sorted(payload.keys()),
        "normalized_amount": round(amount, 2),
        "legacy_constants": dict(EXTRACTED_LEGACY_CONSTANTS),
    }
`;
    generatedFiles['test_migration_parity.py'] = `import unittest
from modernized_app import EXTRACTED_LEGACY_CONSTANTS, run_modernized_logic


class TestMigrationParity(unittest.TestCase):
    def test_parity_valid_payload(self):
        res = run_modernized_logic({"amount": 100, "account_id": "ACC-01"})
        self.assertEqual(res["status"], "migrated_ok")
        self.assertEqual(res["normalized_amount"], 100.0)

    def test_extracted_legacy_baseline_parity(self):
        res = run_modernized_logic({"account_id": "LEGACY-01"})
        self.assertEqual(res["normalized_amount"], round(float(${defaultBaselineAmount}), 2))
        self.assertIsInstance(EXTRACTED_LEGACY_CONSTANTS, dict)

    def test_rejects_negative_amount(self):
        with self.assertRaises(ValueError):
            run_modernized_logic({"amount": -5})


if __name__ == "__main__":
    unittest.main()
`;
  }

  const modernizedNames = Object.keys(generatedFiles);
  const reportMarkdown = [
    '# تقرير تحديث وهجرة الأنظمة القديمة (Legacy Modernization Report)',
    '',
    `- **اللغة المستهدفة:** ${targetLang}`,
    `- **الملفات القديمة المُحلَّلة:** ${detected.map((d) => `${d.path} (${d.language})`).join(', ')}`,
    `- **الثوابت المستخرجة من الكود التراثي:** ${extractedConstants.length > 0 ? extractedConstants.map((c) => `${c.name}=${c.value}`).join(', ') : 'افتراضي (100.0)'}`,
    `- **الملفات الحديثة المُولَّدة:** ${modernizedNames.join(', ')}`,
    '- **حالة اختبارات التطابق (Parity Tests):** جاهزة للتحقق التنفيذي الآلي',
    '',
  ].join('\n');

  generatedFiles['MIGRATION_REPORT.md'] = reportMarkdown;

  return {
    result: {
      legacyDetected: detected,
      modernizedFiles: modernizedNames,
      targetLanguage: targetLang,
      reportMarkdown,
    },
    generatedFiles,
  };
}
